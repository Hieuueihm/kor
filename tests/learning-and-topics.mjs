import { _electron as electron, expect } from '@playwright/test';
import executablePath from 'electron';
import { mkdtemp, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
const env = { ...process.env, HARU_TEST_DATA: await mkdtemp(path.join(tmpdir(), 'haru-topics-')) }; delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ executablePath: process.env.HARU_EXECUTABLE || executablePath, args: process.env.HARU_EXECUTABLE ? [] : ['.'], env });
await mkdir('test-results', { recursive: true });
try {
  const page = await app.firstWindow();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await expect(page.getByRole('heading', { name: 'Học cùng video' })).toBeVisible();
  await page.getByRole('textbox', { name: 'Từ còn thiếu' }).fill('bài đang làm');
  await page.getByRole('textbox', { name: 'Tra từ ngay trong bài', exact: true }).fill('학교');
  await page.locator('.lesson-lookup').getByRole('button', { name: 'Tra nghĩa', exact: true }).click();
  await expect(page.locator('.lesson-lookup-results')).toContainText('Trường học.', { timeout: 20000 });
  await expect(page.getByRole('heading', { name: 'Học cùng video' })).toBeVisible();
  await expect(page.getByRole('textbox', { name: 'Từ còn thiếu' })).toHaveValue('bài đang làm');
  await expect(page.locator('.lesson-lookup').getByRole('button', { name: 'Naver', exact: true })).toBeEnabled();
  await expect(page.locator('.lesson-lookup').getByRole('button', { name: 'Papago', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Lưu nghĩa này', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Nghĩa tiếng Việt' })).toHaveValue('Trường học.');
  await page.getByRole('button', { name: 'Lưu từ mới' }).click();
  await page.getByRole('button', { name: 'Đóng kết quả tra từ', exact: true }).click();
  // The global search also stays on the learning page.
  await page.getByRole('textbox', { name: 'Tra nhanh từ tiếng Hàn', exact: true }).fill('친구');
  await page.locator('.quick-lookup').getByRole('button', { name: 'Tra từ', exact: true }).click();
  await expect(page.locator('.lesson-lookup-word')).toContainText('친구');
  await expect(page.getByRole('textbox', { name: 'Từ còn thiếu' })).toHaveValue('bài đang làm');
  await page.getByRole('button', { name: 'Đóng kết quả tra từ', exact: true }).click();
  await page.locator('nav').getByRole('button', { name: 'Từ vựng chủ đề', exact: true }).click();
  const search = page.getByRole('textbox', { name: 'Tìm chủ đề từ vựng', exact: true });
  await search.fill('do an');
  const library = await page.evaluate(() => window.haru.catalog());
  const foodCount = library.entries.filter(entry => entry.topicIds.includes('food')).length;
  await expect(page.locator('.catalog-entry')).toHaveCount(30);
  await expect(page.locator('.topic-words')).toContainText('Đồ ăn');
  await page.getByRole('button', { name: `Lưu cả nhóm (${foodCount})`, exact: true }).click();
  await expect(page.getByRole('button', { name: 'Đã lưu cả nhóm', exact: true })).toBeDisabled();
  let state = await page.evaluate(() => window.haru.load());
  expect(state.words).toHaveLength(foodCount + 1);
  expect(state.words.filter(word => word.note.startsWith('Chủ đề: Đồ ăn\n'))).toHaveLength(foodCount);
  expect(state.words.filter(word => word.note.startsWith('Chủ đề: Đồ ăn\n')).every(word => word.level === 0 && word.due <= Date.now())).toBe(true);
  await search.fill('학교');
  await expect(page.locator('.topic-word-row').filter({ hasText: '학교' }).getByRole('button', { name: 'Đã lưu', exact: true })).toBeDisabled();
  await search.fill('do uong');
  await expect(page.locator('.catalog-entry')).toHaveCount(30);
  await search.fill('커피');
  await expect(page.locator('.topic-word-row').filter({ has: page.getByRole('button', { name: '커피', exact: true }) })).toHaveCount(1);
  await expect(page.locator('.topic-word-row').filter({ has: page.getByRole('button', { name: '커피', exact: true }) })).toContainText(/cà phê/i);
  await search.fill('chủ đề không tồn tại');
  await expect(page.getByRole('heading', { name: 'Chưa có chủ đề hoặc từ phù hợp' })).toBeVisible();
  await search.fill('đồ ăn');
  await page.screenshot({ path: 'test-results/haru-topic-food.png', fullPage: false });
  state = await page.evaluate(() => window.haru.load()); expect(state.words).toHaveLength(foodCount + 1);
  expect(errors).toEqual([]);
  console.log('PASS: inline lookup and save keep sentence/input intact, header search stays in lesson, topic search accepts Vietnamese without accents and Korean, bulk save deduplicates and schedules flashcards.');
} finally { await app.close(); }
